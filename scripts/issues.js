// Opens one GitHub issue per blocking finding, and closes issues whose finding is gone.
// Runs inside actions/github-script. Env: FINDINGS (path), SOURCE (pr-scan or weekly), CAN_CLOSE ("true"/"false").
const fs = require('fs');
const { owner, repo } = context.repo;
const label = 'mge-security';
const source = process.env.SOURCE;
const run = `${context.serverUrl}/${owner}/${repo}/actions/runs/${context.runId}`;
const data = JSON.parse(fs.readFileSync(process.env.FINDINGS, 'utf8'));
const marker = /<!-- mge-security-id: (\w+) source: ([\w-]+) tool: ([\w-]+) -->/;

try { await github.rest.issues.getLabel({ owner, repo, name: label }); }
catch { await github.rest.issues.createLabel({ owner, repo, name: label, color: 'b60205', description: 'Found by MGE Security' }); }

const existing = await github.paginate(github.rest.issues.listForRepo, { owner, repo, labels: label, state: 'all', per_page: 100 });
const known = new Map();
for (const i of existing) {
  const m = (i.body || '').match(marker);
  if (m && m[2] === source) known.set(m[1], { issue: i, tool: m[3] });
}

// 1. New issues. A finding never gets a second issue, even if its first issue was closed by hand.
let made = 0;
for (const f of data.findings.filter(f => f.blocks && !known.has(f.id))) {
  if (made >= 20) { core.warning('Stopped after 20 new issues; the rest are in the report.'); break; }
  await github.rest.issues.create({ owner, repo, labels: [label],
    title: `[${f.severity}] ${f.title}`.slice(0, 250),
    body: [`**Where:** ${f.where}`, `**Proof:** ${f.proof}`, `**What to do:** ${f.fix}`,
           `Found by ${f.tool} in [this scan](${run}). This issue closes itself when a later full scan no longer finds it.`,
           `<!-- mge-security-id: ${f.id} source: ${source} tool: ${f.tool} -->`].join('\n\n') });
  made++;
}

// 2. Retest: close open issues this scan no longer finds. Only when the tool that found it ran cleanly,
//    so a crashed or skipped tool can never close an issue.
let closed = 0;
if (process.env.CAN_CLOSE === 'true') {
  const current = new Set(data.findings.map(f => f.id));
  for (const [id, { issue, tool }] of known) {
    if (issue.state !== 'open' || current.has(id) || data.tools[tool] !== 'ok') continue;
    await github.rest.issues.createComment({ owner, repo, issue_number: issue.number,
      body: `Retested in [this scan](${run}): no longer found. Closing.\n\n---\n_Generated by MGE Security_` });
    await github.rest.issues.update({ owner, repo, issue_number: issue.number, state: 'closed', state_reason: 'completed' });
    closed++;
  }
}
core.info(`Opened ${made} new issue(s), closed ${closed} fixed issue(s).`);
